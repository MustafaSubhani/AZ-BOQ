"""demo_rules/*.yaml: loading, citation checks, and HARDCODED.md for the developer."""
from functools import lru_cache

import yaml

from . import config

REQUIRED = ("id", "citation")


@lru_cache(maxsize=None)
def load(name: str):
    return yaml.safe_load((config.RULES_DIR / f"{name}.yaml").read_text(encoding="utf-8")) or []


def validate() -> list[str]:
    problems = []
    for p in sorted(config.RULES_DIR.glob("*.yaml")):
        data = yaml.safe_load(p.read_text(encoding="utf-8"))
        if isinstance(data, list):
            for row in data:
                if not isinstance(row, dict) or "id" not in row:
                    continue
                if "sides" in row:
                    for side in row["sides"]:
                        if not side.get("citation"):
                            problems.append(f"{p.name}: {row['id']} side '{side.get('value')}' has no citation")
                elif not row.get("citation"):
                    problems.append(f"{p.name}: {row['id']} has no citation")
    return problems


def project_rule(rule_id: str) -> dict:
    return next(r for r in load("project_rules") if r["id"] == rule_id)


def _known_gaps() -> list[str]:
    """Not hardcoded, just not done: read from the last run so the list cannot go stale."""
    import json
    import os

    from . import store
    from .text.translate import collect_strings, lookup
    out = ["## Known gaps (not hardcoded, not done; from the last run)", ""]
    take = store.get("takeoff") or {"items": []}
    for i in take["items"]:
        if i["value"]["status"] == "blocked":
            out.append(f"- Blocked takeoff item `{i['id']}` ({i['label_en']}): {i['value']['note'] or 'missing ' + ', '.join(i['value']['missing'])}.")
    vision = store.get("vision") or {"files": []}
    unread = [f["rel"].split("/")[-1] for f in vision["files"] if f["status"] != "read for review"]
    if unread:
        out.append(f"- Scans not read ({len(unread)}): {', '.join(unread)}. The vision stage needs OPENAI_API_KEY; "
                   "Tesseract is not installed. Lines that depend on them stay unchecked.")
    if store.get("bill"):
        pending = sum(1 for v in lookup(collect_strings()).values() if v["origin"] == "pending")
        if pending:
            key = "set" if os.environ.get("OPENAI_API_KEY") else "not set"
            out.append(f"- {pending} Azerbaijani strings have no English (OPENAI_API_KEY {key}); run `python -m azboq translate`.")
    conv = store.get("conversion") or {"files": []}
    dis = [f["name"] for f in conv["files"] if f["status"] == "reader disagreement"]
    if dis:
        out.append(f"- {len(dis)} DWGs where LibreDWG and ODA disagree on entity counts; values from them stay in review.")
    exports = config.EXPORT_DIR / "exports.json"
    if exports.exists():
        p = json.loads(exports.read_text(encoding="utf-8")).get("print", {})
        if p and p.get("original_pages") != p.get("written_pages"):
            out.append(f"- The filled bill prints {p.get('written_pages')} pages against the client's {p.get('original_pages')}: "
                       "this Excel wraps some descriptions onto more lines than the client's Excel did. Cells and styles are unchanged.")
    out.append("")
    return out


def write_hardcoded_report() -> str:
    lines = ["# What is hardcoded in this demo", "",
             "Generated by `python -m azboq hardcoded-report` from `backend/demo_rules/`. Not shown in the platform UI.",
             "In the UI, values from these files show as method \"Project rule\" with their citation, never as measured.", ""]
    sections = [
        ("project_rules", "Values a person read from a document the engine cannot read"),
        ("legacy_font_overrides", "Legacy font slots fixed by hand"),
        ("extractors", "Where the engine looks for each takeoff item (rules of where to look; the values come off the drawings)"),
        ("bill_map", "Bill lines linked to takeoff items by hand"),
        ("bill_elements", "Element words read from a bill description"),
        ("conflicts", "Known conflicts between documents, with the suggested side"),
        ("sheet_marks", "Sheet-number marks used to classify sheets"),
        ("layer_roles", "Layer-name patterns and the role each maps to"),
    ]
    for name, title in sections:
        path = config.RULES_DIR / f"{name}.yaml"
        if not path.exists():
            continue
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        lines += [f"## {title}", "", f"File: `demo_rules/{name}.yaml`", ""]
        if isinstance(data, list) and data and isinstance(data[0], dict) and "id" in data[0]:
            lines += ["| id | what | citation | why hardcoded | how to automate |", "|---|---|---|---|---|"]
            for r in data:
                what = r.get("label_en") or r.get("topic") or r.get("slot") or r.get("font") or r.get("type") or ""
                if name == "bill_map":
                    what = f"item {r['item']} ↔ lines {', '.join(r['lines'])} ({r.get('relation', 'equal')})"
                elif name == "bill_elements":
                    what = f"{r['element']}: {r.get('all') or r.get('words') or r.get('any') or r.get('phrases')}"
                elif name == "conflicts":
                    what = f"{r['topic']}: suggested {r.get('suggestion')}"
                elif "value" in r:
                    what = f"{what} = {r['value']} {r.get('unit', '')}".strip()
                lines.append(f"| {r['id']} | {what} | {r.get('citation', '')} | {r.get('why_hardcoded', '')} | "
                             f"{r.get('how_to_automate', '')} |")
        elif isinstance(data, list):
            lines.append(f"{len(data)} patterns.")
        elif isinstance(data, dict):
            lines.append(", ".join(f"{k}: {len(v)}" for k, v in data.items()))
        lines.append("")
    lines += _known_gaps()
    out = "\n".join(lines)
    (config.ROOT / "HARDCODED.md").write_text(out, encoding="utf-8")
    return str(config.ROOT / "HARDCODED.md")
